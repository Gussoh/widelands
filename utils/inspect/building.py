#!/usr/bin/env python3
"""Launch Widelands straight into a building window for quick UI inspection.

Starts a new game for the building's tribe, places the building fully staffed next to
the headquarters, opens its window, switches to the requested tab(s) and saves a
screenshot per tab. By default the game quits afterwards (unattended use); pass --keep
to stay in the game and look around.

Examples:
  utils/inspect/building.py barbarians_coalmine
  utils/inspect/building.py barbarians_coalmine_deep --tabs upgrade outputs
  utils/inspect/building.py empire_sentry --tabs upgrade --keep
  utils/inspect/building.py barbarians_lumberjacks_hut barbarians_coalmine_deep --tabs all
  utils/inspect/building.py --all empire --tabs outputs upgrade   # smoke test a whole tribe
  utils/inspect/building.py barbarians_coalmine --build-menu      # build menu tooltip

Screenshots end up in <build dir>/inspect_home/screenshots/.
"""

import argparse
import os
import shutil
import subprocess
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
GENERATED = os.path.join(REPO, 'test', 'inspect', '_generated')

TEMPLATE = """[global]
map="{map}"
multiplayer="false"
interactive_player="1"
win_condition="endless_game.lua"
peaceful="true"
fogless="true"
custom_starting_positions="false"

[player_1]
tribe="{tribe}"
init="headquarters.lua"
team="0"
closed="false"
"""

SCRIPT = """-- Generated by utils/inspect/building.py. Do not edit.
include "scripting/coroutine.lua"
include "scripting/infrastructure.lua"

local game = wl.Game()
local map = game.map
local mv = wl.ui.MapView()
local buildings = {{ {buildings} }}
local tabs = {{ {tabs} }}
local keep = {keep}
local press = "{press}"
local prefix = "{prefix}"
local wait = {wait}
local build_menu = {build_menu}

local function find_window(serial)
   return mv.windows["building_window_" .. serial]
end

local function shoot(name)
   local file = "screenshots/" .. prefix .. name .. ".png"
   wl.ui.screenshot(file)
   sleep(300)  -- the screenshot is written when the next frame is drawn
   print("INSPECT screenshot: " .. file)
end

run(function()
   sleep(500)
   game.desired_speed = 1000
   local p = game.players[1]
   p.see_all = true
   if buildings[1] == "ALL" then
      -- Smoke test mode: every production, training and military site of the tribe
      buildings = {{}}
      for _, d in ipairs(p.tribe.buildings) do
         if d.type_name == "productionsite" or d.type_name == "trainingsite" or
            d.type_name == "militarysite" then
            table.insert(buildings, d.name)
         end
      end
      print("INSPECT checking " .. #buildings .. " buildings")
   end
   local hq = map.player_slots[1].starting_field
   -- Clear room to the east of the HQ and put the building there.
   local spot = map:get_field((hq.x + 6) % map.width, hq.y)
   -- Remove trees, rocks etc. (but no buildings, flags or roads) around the spot and along
   -- the way back to the HQ so that a road can be built.
   local function clear(center, radius)
      for _, f in ipairs(center:region(radius)) do
         if f.immovable and f.immovable.descr.type_name == "immovable" then
            pcall(function() f.immovable:remove() end)
         end
      end
   end
   -- Build menu mode: hover over each building in the build menu and screenshot its tooltip.
   local function inspect_build_menu(name)
      local d = wl.Game():get_building_description(name)
      local cap = d.is_mine and "mine" or d.size
      local target = nil
      for _, f in ipairs(hq:region(14, 4)) do
         if f:has_max_caps(cap) then
            p:conquer(f, 2)
            clear(f, 2)
            if f:has_caps(cap) then
               target = f
               break
            end
         end
      end
      if not target then
         print("INSPECT error: no place to build " .. name)
         return
      end
      mv:scroll_to_field(target)
      sleep(800)
      mv:click(target)
      sleep(800)
      local w = mv.windows["field_action"]
      if not w then
         print("INSPECT error: build menu did not open for " .. name)
         return
      end
      local tab = w.tabs[d.is_mine and "mines" or d.size]
      if tab then tab:click() end
      sleep(400)
      local btn = w.buttons[name]
      if not btn then
         print("INSPECT error: " .. name .. " is not in the build menu")
      else
         local x, y = mv:get_descendant_position(btn)
         wl.ui.mouse_move(x + btn.width // 2, y + btn.height // 2)
         sleep(1500)
         shoot(name .. "_buildmenu")
      end
      w:close()
      sleep(300)
   end

   for i, name in ipairs(buildings) do
      if build_menu then
         inspect_build_menu(name)
         goto continue
      end
      clear(spot, 2)
      clear(hq.brn.rn.rn.rn, 3)
      local b = prefilled_buildings(p, {{ name, spot.x, spot.y }})[1]
      -- Connect to the HQ flag (6 steps west) so the building is part of the HQ's economy.
      local ok, err = pcall(connected_road, "normal", p, b.flag, "l,l,l|l,l,l", true)
      if not ok then print("INSPECT note: could not build road: " .. tostring(err)) end
      if wait > 0 then
         -- Let the building work for a while (fast-forwarded) so it shows a real status
         game.desired_speed = 10000
         sleep(wait * 1000)
         game.desired_speed = 1000
      end
      mv:scroll_to_field(spot)
      sleep(800)
      mv:click(spot)
      sleep(800)
      local w = find_window(b.serial)
      if not w then
         print("INSPECT error: window for " .. name .. " did not open")
      else
         w.position_x = 40
         w.position_y = 60
         local wanted = tabs
         if #wanted == 1 and wanted[1] == "all" then
            wanted = {{}}
            for tabname, _ in pairs(w.tabs) do table.insert(wanted, tabname) end
            table.sort(wanted)
         end
         for _, tabname in ipairs(wanted) do
            local tab = w.tabs[tabname]
            if tab then
               tab:click()
               sleep(400)
               shoot(name .. "_" .. tabname)
            else
               print("INSPECT note: " .. name .. " has no tab '" .. tabname .. "'")
            end
         end
         if press ~= "" then
            local btn = w.buttons[press]
            if btn then
               btn:click()
               sleep(600)
               shoot(name .. "_pressed_" .. press)
            else
               print("INSPECT note: " .. name .. " has no button '" .. press .. "'")
            end
         end
         if not keep and i < #buildings then
            w:close()
         end
      end
      if i < #buildings then
         b:destroy()
         sleep(300)
      end
      ::continue::
   end
   print("INSPECT done")
   if not keep then
      mv:close()
   end
end)
"""


def find_binary(build_dir):
    for name in ('widelands.exe', 'widelands'):
        for candidate in (os.path.join(build_dir, 'src', name), os.path.join(build_dir, name),
                          os.path.join(REPO, name)):
            if os.path.isfile(candidate):
                return candidate
    return None


def lua_list(items):
    return ', '.join('"{}"'.format(i) for i in items)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('buildings', nargs='*', help='internal building names, e.g. '
                        'barbarians_coalmine. All must belong to the same tribe.')
    parser.add_argument('--tabs', nargs='+', default=['all'],
                        help='tab names to screenshot (e.g. outputs upgrade wares workers '
                        'soldiers), or "all" (default)')
    parser.add_argument('--keep', action='store_true',
                        help='keep the game running afterwards instead of quitting')
    parser.add_argument('--map', default='maps/Crater.wmf', help='map to play on')
    parser.add_argument('--build-dir', default=os.path.join(REPO, 'build'),
                        help='CMake build directory containing the widelands binary')
    parser.add_argument('--resolution', default='1280x800', help='window size WxH')
    parser.add_argument('--press', metavar='BUTTON', default='',
                        help='after the tabs, click the button with this name in the building '
                        'window (e.g. upgrade_now) and take another screenshot')
    parser.add_argument('--all', metavar='TRIBE',
                        help='smoke test: open every production/training/military site of '
                        'TRIBE instead of the listed buildings')
    parser.add_argument('--binary', help='run this widelands executable instead of the one in '
                        '--build-dir (e.g. a saved copy of an older build, for comparisons)')
    parser.add_argument('--wait', type=int, default=0, metavar='SECONDS',
                        help='game seconds to let each building work (fast-forwarded) before '
                        'opening its window')
    parser.add_argument('--build-menu', action='store_true',
                        help='instead of opening the building windows, hover over each building '
                        'in the build menu and screenshot its tooltip')
    parser.add_argument('--prefix', default='',
                        help='prefix for screenshot file names, e.g. "before_"')
    args = parser.parse_args()

    if args.all:
        args.buildings = ['ALL']
        tribe = args.all
    elif not args.buildings:
        parser.error('name at least one building, or use --all TRIBE')
    else:
        tribe = args.buildings[0].split('_')[0]
        if any(b.split('_')[0] != tribe for b in args.buildings):
            sys.exit('All buildings must belong to the same tribe.')

    binary = os.path.abspath(args.binary) if args.binary else find_binary(args.build_dir)
    if binary is None or not os.path.isfile(binary):
        sys.exit('Could not find the widelands binary: ' + str(binary or args.build_dir))

    os.makedirs(GENERATED, exist_ok=True)
    with open(os.path.join(GENERATED, 'inspect.wgt'), 'w', newline='\n') as f:
        f.write(TEMPLATE.format(map=args.map, tribe=tribe))
    with open(os.path.join(GENERATED, 'inspect.lua'), 'w', newline='\n') as f:
        f.write(SCRIPT.format(buildings=lua_list(args.buildings), tabs=lua_list(args.tabs),
                              keep='true' if args.keep else 'false', press=args.press, prefix=args.prefix, wait=args.wait,
                              build_menu='true' if args.build_menu else 'false'))

    home = os.path.join(args.build_dir, 'inspect_home')
    os.makedirs(home, exist_ok=True)
    width, height = args.resolution.split('x')
    cmd = [binary,
           '--datadir=' + os.path.join(REPO, 'data'),
           '--datadir_for_testing=' + REPO,
           '--homedir=' + home,
           '--nosound',
           '--language=en',
           '--xres=' + width,
           '--yres=' + height,
           '--new_game_from_template=test/inspect/_generated/inspect.wgt',
           '--script=test/inspect/_generated/inspect.lua']
    print(' '.join(cmd))
    env = dict(os.environ)
    mingw_bin = r'C:\msys64\mingw64\bin'
    if os.name == 'nt' and os.path.isdir(mingw_bin):
        env['PATH'] = mingw_bin + os.pathsep + env.get('PATH', '')  # runtime DLLs
    proc = subprocess.run(cmd, cwd=REPO, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True, errors='replace', env=env)
    # Widelands writes its log (including Lua print()) to stdout.txt in the home directory.
    log = os.path.join(home, 'stdout.txt')
    output = proc.stdout
    if os.path.exists(log):
        with open(log, encoding='utf-8', errors='replace') as f:
            output = f.read()
    shots = []
    for line in output.splitlines():
        if 'INSPECT' in line or 'ERROR' in line or 'LUA ERROR' in line:
            print(line)
        if 'INSPECT screenshot: ' in line:
            shots.append(os.path.join(home, line.split('INSPECT screenshot: ')[1].strip()))
    print('Log:', log)
    for s in shots:
        print('Screenshot:', s if os.path.exists(s) else s + ' (missing!)')
    return proc.returncode


if __name__ == '__main__':
    sys.exit(main())
